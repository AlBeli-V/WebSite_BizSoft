#!/usr/bin/env bash
# Решение сторожа утренних контуров: пора запускать конвейер или нет.
#
# Зачем. Планировщик GitHub Actions в этом репозитории задерживает cron-слоты
# в среднем на 4–5 часов (замер 04–05.09.2026: слот 06:35 → прогон 11:39).
# Утренний отчёт из-за этого приходил к обеду. Ждать внутри job нельзя —
# репозиторий приватный, ожидание тарифицируется поминутно.
#
# Отсюда сторож: он запускается каждый час в окне ночь–утро, просыпается на
# секунды и сам решает, наступило ли время. Какой бы ни была задержка,
# один из часовых слотов попадёт в целевое окно.
#
#   morning_gate.sh <час МСК> <дата МСК> <маркер last-mailed>
#
# Печатает "run" или "skip" и причину. Решение отделено от workflow, чтобы
# его можно было проверить тестами, а не только в проде.
set -euo pipefail

hour=${1:?час МСК}
today=${2:?дата МСК}
mailed=${3-}

# Окно запуска — 09:00–13:59 МСК. Раньше девяти письмо не нужно: данные за
# сутки ещё не полны. Позже двух дня запускать бессмысленно — к этому времени
# успевает сработать и штатный cron-слот с его задержкой.
if [ "$((10#$hour))" -lt 9 ] || [ "$((10#$hour))" -gt 13 ]; then
  echo "skip: вне окна запуска (сейчас ${hour}:xx МСК, окно 09–13)"
  exit 0
fi

if [ "$mailed" = "$today" ]; then
  echo "skip: письмо за $today уже отправлено"
  exit 0
fi

echo "run: окно 09–13 МСК, письмо за $today ещё не отправлено"
