"""Что именно сделать по каждому выявленному разрыву.

Раньше отчёт заканчивался ярлыком: «ранняя возможность», «новая посадочная
страница или материал». Ярлык называет класс задачи, но не задачу: из него
нельзя ни начать работу, ни понять, когда она закончена. Руководитель читал
список разрывов и не находил в нём ни одного действия, которое можно отдать
в работу.

Здесь из класса разрыва и данных кластера собирается три вещи:

* шаг — что сделать, с конкретным адресом и фразой, а не общим словом;
* промт — готовый текст задания, который копируется и отправляется в работу
  как есть, без досочинения;
* признак завершения — измеримый, иначе задача не закрывается никогда.

Срок проверки считается от природы работы, а не назначается на глаз: правка
сниппета видна после переобхода, новая страница — после индексации.
"""
from __future__ import annotations

import datetime as dt

#: Сколько ждать результата по каждому классу, дней.
CHECK_AFTER = {
    "GAP-A": 21, "GAP-B": 10, "GAP-C": 21, "GAP-D": 7,
    "GAP-E": 14, "GAP-F": 30, "GAP-G": 21, "GAP-H": 30,
}


def _num(n: int | float | None) -> str:
    return f"{int(n):,}".replace(",", " ") if n else "0"


def build(gap: dict, today: str) -> dict:
    """Шаг, промт и признак завершения по одному разрыву."""
    cls = gap.get("gap", "")
    cluster = gap.get("cluster", "")
    phrase = (gap.get("top_phrases") or [{}])[0].get("phrase") or cluster
    demand = gap.get("commercial_demand") or 0
    url = gap.get("url") or ""
    pos = gap.get("best_position")
    imp = gap.get("impressions") or 0
    clicks = gap.get("clicks") or 0
    due = (dt.date.fromisoformat(today)
           + dt.timedelta(days=CHECK_AFTER.get(cls, 21))).isoformat()

    if cls in ("GAP-A", "GAP-G"):
        step = (f"Завести страницу под «{phrase}» — {_num(demand)} запросов в месяц; "
                f"сейчас своей страницы нет")
        prompt = (
            f"Создай посадочную страницу под кластер «{cluster}». Ведущая фраза — "
            f"«{phrase}», измеренный покупательский спрос {_num(demand)} запросов в месяц. "
            "Проверь по src/data/vendors.ts, что вендора действительно нет в каталоге, "
            "и по reports/seo/wordstat/decisions.json — что решение по нему не принято. "
            "Прежде чем заводить: подтверди, что вендор принимает оплату картой или "
            "через наш зарубежный счёт, иначе спрос в сделку не превратится. "
            "Сделай карточку вендора, перелинкуй с разделом назначения ПО, добавь в "
            "sitemap и запроси переобход через ops-yandex-recrawl. "
            "Заведи эксперимент в reports/seo/intelligence/seo-experiments.json "
            f"с собственной датой старта и контрольной датой {due}.")
        success = (f"страница в индексе Яндекса и показы по «{phrase}» больше нуля "
                   f"к {due}")

    elif cls == "GAP-B":
        step = f"Разобраться, почему {url} не индексируется"
        prompt = (
            f"Страница {url} существует, но не в индексе. Проверь через ops-* workflow: "
            "код ответа, robots.txt, meta robots, canonical, наличие в sitemap.xml, "
            "статус в Яндекс.Вебмастере. Найди причину, устрани и запроси переобход "
            f"через ops-yandex-recrawl. Контрольная дата {due}.")
        success = f"страница в индексе к {due}"

    elif cls == "GAP-C":
        step = (f"Переписать {url} под «{phrase}» — позиция "
                f"{pos if pos is not None else 'вне топ-100'}")
        prompt = (
            f"Страница {url} в индексе, но по «{phrase}» стоит на позиции "
            f"{pos if pos is not None else 'вне топ-100'} при спросе {_num(demand)} "
            "запросов в месяц. Перепиши заголовок, описание и первый экран под эту "
            "фразу, добавь блок вопросов и внутренние ссылки из смежных карточек. "
            "Одна правка — одна проверяемая гипотеза; занеси её в реестр "
            f"экспериментов с контрольной датой {due}.")
        success = f"позиция по «{phrase}» выше текущей к {due}"

    elif cls == "GAP-D":
        step = (f"Переписать сниппет {url}: {_num(imp)} показов, "
                f"{_num(clicks)} переходов")
        prompt = (
            f"У {url} позиция {pos} по «{phrase}» и {_num(imp)} показов, но всего "
            f"{_num(clicks)} переходов — люди видят нас в выдаче и не заходят. "
            "Перепиши title и description под коммерческий интент: оплата на юрлицо, "
            "счёт, договор, ЭДО. Ядро title не длиннее 65 символов, description до 160. "
            f"Заведи как отдельный эксперимент со своей датой старта, контроль {due}. "
            "Важно: выкат на сайте не равен обновлению сниппета в выдаче — "
            "фиксируй их раздельно.")
        success = f"CTR по «{phrase}» выше текущего при том же объёме показов к {due}"

    elif cls == "GAP-E":
        step = f"Разобраться, почему трафик на {url} не превращается в обращения"
        prompt = (
            f"На {url} есть переходы, но нет обращений. Проверь: виден ли блок с ценой "
            "и условиями на первом экране, есть ли форма и кнопка запроса КП, работают "
            "ли цели add_to_cart и quote_pdf на этой странице. Предложи одну правку "
            f"предложения или формы и заведи её экспериментом с контролем {due}.")
        success = f"обращения с {url} появились к {due}"

    elif cls == "GAP-F":
        step = (f"Оценить платный канал по «{phrase}» — {_num(demand)} запросов "
                "в месяц, органика будет долгой")
        prompt = (
            f"По «{phrase}» спрос {_num(demand)} запросов в месяц, органика займёт "
            "месяцы. Подготовь расчёт платного канала: оценка ставки, прогноз "
            "стоимости обращения, месячный бюджет. Только расчёт — запуск рекламы "
            "и бюджет решает руководитель, рекламные кабинеты не трогать.")
        success = "расчёт на столе у руководителя, решение о запуске за ним"

    else:  # GAP-H
        step = f"Спрос по «{phrase}» снижается — снять с приоритета, наблюдать"
        prompt = (
            f"Спрос по кластеру «{cluster}» снижается. Ничего не делать: убрать из "
            f"плана работ и вернуться к замеру {due}. Если снижение продолжится "
            "два замера подряд, предложи вывести направление из мониторинга.")
        success = f"повторный замер {due} подтвердил или опроверг снижение"

    return {"step": step, "prompt": prompt, "success": success, "check_on": due}
