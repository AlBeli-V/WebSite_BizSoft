/**
 * Выключатель WebMCP-слоя (kill switch).
 *
 * По образцу src/lib/zoho-hub.ts: слой включён по умолчанию и «выключается
 * значением», а не «включается наличием» переменной — иначе прод-сборка,
 * до которой переменная не доехала (ловушка BLD-002), молча вырезала бы
 * весь слой минификатором.
 *
 * Погасить WebMCP целиком (и регистрацию инструментов в браузере,
 * и API-эндпоинт), не трогая остальной сайт:
 *
 *     PUBLIC_WEBMCP=0
 *
 * в astro.env на сервере + пересборка (deploy.sh подхватывает переменные
 * до docker build). Сайт для людей, SEO-разметка и аналитика при любом
 * положении рубильника работают без изменений.
 */

/** Клиентская и сборочная сторона (вшивается Vite на этапе сборки). */
export const WEBMCP_ENABLED = import.meta.env.PUBLIC_WEBMCP !== '0';

/**
 * Серверная сторона (эндпоинт /api/agent): сначала рантайм-окружение
 * процесса, затем сборочное значение — как в lib/directus.ts, чтобы
 * прод-окружение Docker могло погасить API без пересборки.
 */
export function webmcpApiEnabled(): boolean {
  const runtime = process.env.PUBLIC_WEBMCP;
  if (runtime !== undefined) return runtime !== '0';
  return WEBMCP_ENABLED;
}
