/**
 * Обращение в коммерческом предложении.
 *
 * Имя приходит из формы заявки как есть: «Екатерина Кувшинова»,
 * «Иванов Иван Иванович», «Иван», иногда с должностью или лишними словами.
 * Из этого нужно собрать живое обращение — «Уважаемая Екатерина!».
 *
 * Род определяется по отчеству, если оно есть: -вич и -вна дают ответ
 * однозначно. Если отчества нет — по окончанию имени, но только для
 * уверенных случаев. Когда уверенности нет, форма пишется через скобку:
 * ошибиться в роде в первой строке письма хуже, чем выглядеть формально.
 */

const MALE_PATRONYMIC = /(вич|ич|оглы|улы)$/i;
const FEMALE_PATRONYMIC = /(вна|чна|кызы|гызы)$/i;

/** Женские имена на согласную и мужские на -а: список короче, чем правило. */
const FEMALE_EXCEPTIONS = new Set([
  'любовь', 'нинель', 'нинэль', 'рахиль', 'суламифь', 'эсфирь', 'юдифь',
  'адель', 'жизель', 'мишель', 'ассоль', 'нэлль', 'айгуль', 'гульнур',
]);
const MALE_EXCEPTIONS = new Set([
  'никита', 'илья', 'фома', 'кузьма', 'савва', 'лука', 'данила', 'гаврила',
  'мустафа', 'муса', 'иса', 'юша', 'аслан-мурза',
]);

/** Слова, которые в поле имени встречаются, но именем не являются. */
const NOT_A_NAME = /^(ооо|оао|зао|ип|ао|пао|нко|фгуп|гбу|мбу|компания|фирма|отдел|директор|менеджер|специалист|руководитель|бухгалтер)$/i;

/** Правовая форма в поле имени: значит, вписали организацию, а не человека. */
const ORG_FORM = /^(ооо|оао|зао|пао|ао|ип|нко|фгуп|гбу|мбу)$/i;

/**
 * Распространённые имена.
 *
 * Отделять имя от фамилии по окончанию нельзя: «Екатерина», «Полина»,
 * «Ангелина» кончаются на -ина ровно как фамилии «Кувшинова» и «Фомина».
 * Правило по окончанию вычёркивало имя вместе с фамилией и оставляло
 * обращение «Уважаемая Кувшинова». Список короче и вернее.
 */
const KNOWN_NAMES = new Set([
  'александр', 'алексей', 'анатолий', 'андрей', 'антон', 'аркадий', 'арсений',
  'артём', 'артем', 'артур', 'борис', 'вадим', 'валентин', 'валерий', 'василий',
  'виктор', 'виталий', 'владимир', 'владислав', 'вячеслав', 'геннадий', 'георгий',
  'глеб', 'григорий', 'даниил', 'данила', 'денис', 'дмитрий', 'евгений', 'егор',
  'иван', 'игорь', 'илья', 'кирилл', 'константин', 'лев', 'леонид', 'максим',
  'марк', 'матвей', 'михаил', 'никита', 'николай', 'олег', 'павел', 'пётр',
  'петр', 'роман', 'руслан', 'сергей', 'станислав', 'степан', 'тимофей', 'тимур',
  'фёдор', 'федор', 'филипп', 'эдуард', 'юрий', 'ярослав',
  'александра', 'алёна', 'алена', 'алина', 'алиса', 'алла', 'анастасия', 'ангелина',
  'анна', 'антонина', 'валентина', 'валерия', 'варвара', 'вера', 'вероника',
  'виктория', 'галина', 'дарья', 'диана', 'ева', 'евгения', 'екатерина', 'елена',
  'елизавета', 'жанна', 'зинаида', 'инна', 'ирина', 'карина', 'кристина', 'ксения',
  'лариса', 'лидия', 'любовь', 'людмила', 'маргарита', 'марина', 'мария', 'надежда',
  'наталья', 'наталия', 'нина', 'оксана', 'ольга', 'полина', 'раиса', 'регина',
  'светлана', 'софья', 'софия', 'таисия', 'тамара', 'татьяна', 'ульяна', 'юлия', 'яна',
]);

export type Gender = 'male' | 'female' | 'unknown';

/** Разобрать поле имени на слова, отбросив явно не-имена. */
export function nameParts(raw: string): string[] {
  return (raw || '')
    .replace(/[«»"'()]/g, ' ')
    .split(/[\s,]+/)
    .map((w) => w.trim())
    .filter((w) => w.length > 1 && !NOT_A_NAME.test(w) && /[А-Яа-яЁёA-Za-z]/.test(w));
}

export function detectGender(raw: string): Gender {
  const parts = nameParts(raw);
  for (const w of parts) {
    const l = w.toLowerCase();
    if (FEMALE_PATRONYMIC.test(l)) return 'female';
    if (MALE_PATRONYMIC.test(l)) return 'male';
  }
  const known = parts.find((w) => KNOWN_NAMES.has(w.toLowerCase()));
  const ordered = known ? [known, ...parts] : parts;
  for (const w of ordered) {
    const l = w.toLowerCase();
    if (FEMALE_EXCEPTIONS.has(l)) return 'female';
    if (MALE_EXCEPTIONS.has(l)) return 'male';
    // Имя на -а/-я почти всегда женское, на согласную — мужское.
    // Проверяем только первое похожее на имя слово: фамилия склоняется иначе.
    if (/^[а-яё]+$/i.test(l)) {
      if (/(ия|ья|на|ла|ра|та|са|ка|га|да|ва|за|ма|па|фа|ха|ца|ча|ша|ща|а|я)$/.test(l)) return 'female';
      return 'male';
    }
  }
  return 'unknown';
}

/**
 * Имя для обращения.
 *
 * Берём имя, а при наличии отчества — имя с отчеством: в деловом письме это
 * привычнее и уважительнее. Порядок слов в поле бывает любым, поэтому имя
 * ищем как слово, стоящее рядом с отчеством, а не по позиции.
 */
export function addressName(raw: string): string {
  const parts = nameParts(raw);
  if (!parts.length) return '';
  const patrIdx = parts.findIndex(
    (w) => MALE_PATRONYMIC.test(w) || FEMALE_PATRONYMIC.test(w));
  if (patrIdx > 0) return `${parts[patrIdx - 1]} ${parts[patrIdx]}`;

  // Без отчества порядок слов произволен: «Иванов Иван» и «Иван Иванов»
  // встречаются одинаково часто. Ищем known-имя в любой позиции.
  const known = parts.find((w) => KNOWN_NAMES.has(w.toLowerCase()));
  if (known) return known;

  // Имя не узнали — обращаемся тем, что дали, но не больше двух слов:
  // выдумывать, какое из слов имя, значит ошибаться в первой строке письма.
  return parts.slice(0, 2).join(' ');
}

/** «Уважаемая Екатерина» / «Уважаемый Иван Иванович» / «Уважаемый(ая) Ким». */
export function salutation(raw: string): string {
  // В поле контактного лица нередко вписывают организацию. Обращаться
  // «Уважаемая Ромашка» к ООО «Ромашка» хуже, чем нейтральное приветствие.
  // Проверяем по словам, а не через \b: в JS граница слова определена для
  // латиницы, и на кириллице такая проверка молча не срабатывает.
  const words = (raw || '').replace(/[«»"'()]/g, ' ').split(/[\s,.]+/);
  if (words.some((w) => ORG_FORM.test(w))) return 'Уважаемые господа!';
  const name = addressName(raw);
  if (!name) return 'Уважаемые господа!';
  const g = detectGender(raw);
  const word = g === 'female' ? 'Уважаемая' : g === 'male' ? 'Уважаемый' : 'Уважаемый(ая)';
  return `${word} ${name}!`;
}
