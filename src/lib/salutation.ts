/**
 * Обращение в коммерческом предложении и разбор поля ФИО.
 *
 * Имя приходит из формы заявки как есть: «Екатерина Кувшинова»,
 * «Иванов Иван Иванович», «Иван», «Беляев А.В.», иногда с должностью или
 * лишними словами. Из этого нужно собрать живое обращение — «Уважаемая
 * Екатерина!» — и сокращённое «Беляев А.В.» для блока «Кому» в документе.
 *
 * Правило руководителя 16.09.2026: обращаемся тем, что знаем наверняка.
 * Есть имя и отчество — «Уважаемый Иван Иванович!». Есть только имя —
 * «Уважаемый Иван!». Фамилия с инициалами или одна фамилия — «Уважаемый
 * коллега!»: называть человека по фамилии в первой строке письма хуже, чем
 * обратиться нейтрально.
 *
 * Род определяется по отчеству, если оно есть: -вич и -вна дают ответ
 * однозначно. Если отчества нет — по окончанию имени, но только для
 * уверенных случаев. Когда уверенности нет, форма пишется через скобку:
 * ошибиться в роде в первой строке письма хуже, чем выглядеть формально.
 */

const MALE_PATRONYMIC = /(вич|ич|оглы|улы)$/i;
const FEMALE_PATRONYMIC = /(вна|чна|кызы|гызы)$/i;

/** Женские имена на согласную и мужские на -а: список короче, чем правило. */
const FEMALE_EXCEPTIONS = new Set([
  'любовь', 'нинель', 'нинэль', 'рахиль', 'суламифь', 'эсфирь', 'юдифь',
  'адель', 'жизель', 'мишель', 'ассоль', 'нэлль', 'айгуль', 'гульнур',
]);
const MALE_EXCEPTIONS = new Set([
  'никита', 'илья', 'фома', 'кузьма', 'савва', 'лука', 'данила', 'гаврила',
  'мустафа', 'муса', 'иса', 'юша', 'аслан-мурза',
]);

/**
 * Инициалы: «А.», «А.В.», «АВ». Именем не являются, но в поле ФИО приходят
 * часто — по ним собирается сокращённая запись, а обращение по ним не строим.
 */
const INITIALS = /^(?:[А-ЯЁA-Z]\.?){1,3}$/;

/**
 * Окончания фамилий. Нужны там, где имя не узналось по списку: одно слово
 * «Ратмир» это имя, а «Ратмиров» — фамилия, и обращаться «Уважаемый
 * Ратмиров!» нельзя. Проверяются только после списка имён: «Валерий» и
 * «Юрий» кончаются на -ий ровно как «Раевский».
 */
const SURNAME_END = /(ов|ёв|ев|ин|ын|ова|ёва|ева|ина|ына|ский|ская|цкий|цкая|ской|ко|ук|юк|чук|ян|дзе|швили|иди|их|ых|ец|ук|ак|як)$/i;

/** Слова, которые в поле имени встречаются, но именем не являются. */
const NOT_A_NAME = /^(ооо|оао|зао|ип|ао|пао|нко|фгуп|гбу|мбу|компания|фирма|отдел|директор|менеджер|специалист|руководитель|бухгалтер)$/i;

/** Правовая форма в поле имени: значит, вписали организацию, а не человека. */
const ORG_FORM = /^(ооо|оао|зао|пао|ао|ип|нко|фгуп|гбу|мбу)$/i;

/**
 * Распространённые имена.
 *
 * Отделять имя от фамилии по окончанию нельзя: «Екатерина», «Полина»,
 * «Ангелина» кончаются на -ина ровно как фамилии «Кувшинова» и «Фомина».
 * Правило по окончанию вычёркивало имя вместе с фамилией и оставляло
 * обращение «Уважаемая Кувшинова». Список короче и вернее.
 */
const KNOWN_NAMES = new Set([
  'александр', 'алексей', 'анатолий', 'андрей', 'антон', 'аркадий', 'арсений',
  'артём', 'артем', 'артур', 'борис', 'вадим', 'валентин', 'валерий', 'василий',
  'виктор', 'виталий', 'владимир', 'владислав', 'вячеслав', 'геннадий', 'георгий',
  'глеб', 'григорий', 'даниил', 'данила', 'денис', 'дмитрий', 'евгений', 'егор',
  'иван', 'игорь', 'илья', 'кирилл', 'константин', 'лев', 'леонид', 'максим',
  'марк', 'матвей', 'михаил', 'никита', 'николай', 'олег', 'павел', 'пётр',
  'петр', 'роман', 'руслан', 'сергей', 'станислав', 'степан', 'тимофей', 'тимур',
  'фёдор', 'федор', 'филипп', 'эдуард', 'юрий', 'ярослав',
  'александра', 'алёна', 'алена', 'алина', 'алиса', 'алла', 'анастасия', 'ангелина',
  'анна', 'антонина', 'валентина', 'валерия', 'варвара', 'вера', 'вероника',
  'виктория', 'галина', 'дарья', 'диана', 'ева', 'евгения', 'екатерина', 'елена',
  'елизавета', 'жанна', 'зинаида', 'инна', 'ирина', 'карина', 'кристина', 'ксения',
  'лариса', 'лидия', 'любовь', 'людмила', 'маргарита', 'марина', 'мария', 'надежда',
  'наталья', 'наталия', 'нина', 'оксана', 'ольга', 'полина', 'раиса', 'регина',
  'светлана', 'софья', 'софия', 'таисия', 'тамара', 'татьяна', 'ульяна', 'юлия', 'яна',
]);

export type Gender = 'male' | 'female' | 'unknown';

/** Инициалы в любом регистре — нужны, чтобы «а.в.» стало «А.В.», а не «А.в.». */
const INITIALS_ANY = /^(?:[А-ЯЁA-Zа-яёa-z]\.){1,3}$/;

/**
 * Регистр слова в имени.
 *
 * В форме заявки набирают как придётся: «беляев алексей», «БЕЛЯЕВ АЛЕКСЕЙ»,
 * «Беляев алексей». В коммерческое предложение и в обращение письма это
 * уходило дословно, и документ выглядел небрежно (замечание руководителя
 * 19.09.2026).
 *
 * Правим только очевидное: слово целиком строчными или целиком прописными
 * приводим к прописной первой букве. Смешанный регистр не трогаем — его
 * набрали намеренно, и «МакДональд» после приведения стал бы «Макдональд».
 * Составные фамилии и имена через дефис получают прописную в каждой части:
 * «петров-водкин» → «Петров-Водкин».
 */
export function capitalizeName(word: string): string {
  if (INITIALS_ANY.test(word)) return word.toUpperCase();
  const hasUpper = /[А-ЯЁA-Z]/.test(word);
  const hasLower = /[а-яёa-z]/.test(word);
  if (hasUpper && hasLower) return word;
  return word
    .split(/([-\u2019'])/)
    .map((part) => (/^[-\u2019']$/.test(part)
      ? part
      : part.charAt(0).toUpperCase() + part.slice(1).toLowerCase()))
    .join('');
}

/**
 * Разобрать поле имени на слова, отбросив явно не-имена.
 *
 * Регистр приводится здесь, на входе: дальше поле разбирают и склеивают
 * несколько функций, и починка в каждой из них рано или поздно разъехалась бы.
 */
export function nameParts(raw: string): string[] {
  return (raw || '')
    .replace(/[«»"'()]/g, ' ')
    .split(/[\s,]+/)
    .map((w) => w.trim())
    .filter((w) => w.length > 1 && !NOT_A_NAME.test(w) && /[А-Яа-яЁёA-Za-z]/.test(w))
    .map(capitalizeName);
}

export function detectGender(raw: string): Gender {
  const parts = nameParts(raw);
  for (const w of parts) {
    const l = w.toLowerCase();
    if (FEMALE_PATRONYMIC.test(l)) return 'female';
    if (MALE_PATRONYMIC.test(l)) return 'male';
  }
  const known = parts.find((w) => KNOWN_NAMES.has(w.toLowerCase()));
  const ordered = known ? [known, ...parts] : parts;
  for (const w of ordered) {
    const l = w.toLowerCase();
    if (FEMALE_EXCEPTIONS.has(l)) return 'female';
    if (MALE_EXCEPTIONS.has(l)) return 'male';
    // Имя на -а/-я почти всегда женское, на согласную — мужское.
    // Проверяем только первое похожее на имя слово: фамилия склоняется иначе.
    if (/^[а-яё]+$/i.test(l)) {
      if (/(ия|ья|на|ла|ра|та|са|ка|га|да|ва|за|ма|па|фа|ха|ца|ча|ша|ща|а|я)$/.test(l)) return 'female';
      return 'male';
    }
  }
  return 'unknown';
}

/**
 * Имя для обращения.
 *
 * Берём имя, а при наличии отчества — имя с отчеством: в деловом письме это
 * привычнее и уважительнее. Порядок слов в поле бывает любым, поэтому имя
 * ищем как слово, стоящее рядом с отчеством, а не по позиции.
 */
export function addressName(raw: string): string {
  const p = parsePerson(raw);
  if (p.first && p.patronymic) return `${p.first} ${p.patronymic}`;
  return p.first;
}

export interface PersonName {
  surname: string;
  first: string;
  patronymic: string;
  /** Инициалы, если пришли вместо имени: «А.В.». */
  initials: string;
}

/**
 * Разобрать поле ФИО на фамилию, имя и отчество.
 *
 * Порядок слов в форме произволен — «Иванов Иван Иванович» и «Иван Иванов»
 * встречаются одинаково часто, поэтому опираемся не на позицию, а на
 * признаки: отчество узнаётся по окончанию, имя — по списку и по соседству
 * с отчеством, фамилия — по окончанию или по остатку.
 */
export function parsePerson(raw: string): PersonName {
  const all = nameParts(raw);
  const initials = all.filter((w) => INITIALS.test(w)).join('');
  const parts = all.filter((w) => !INITIALS.test(w));
  const out: PersonName = { surname: '', first: '', patronymic: '', initials };
  if (!parts.length) return out;

  const patrIdx = parts.findIndex(
    (w) => MALE_PATRONYMIC.test(w) || FEMALE_PATRONYMIC.test(w));
  if (patrIdx >= 0) out.patronymic = parts[patrIdx];

  const rest = parts.filter((_, i) => i !== patrIdx);
  // Имя: сначала по списку, затем — слово перед отчеством. «Иванов Иван
  // Иванович» и «Иван Иванович» разбираются одинаково.
  const known = rest.find((w) => KNOWN_NAMES.has(w.toLowerCase()));
  if (known) out.first = known;
  else if (patrIdx > 0) out.first = parts[patrIdx - 1];

  const left = rest.filter((w) => w !== out.first);
  if (left.length) {
    // Фамилия — слово с фамильным окончанием, иначе первое из оставшихся.
    out.surname = left.find((w) => SURNAME_END.test(w)) || left[0];
  }
  // Одно слово без отчества и не из списка: «Ратмиров» — фамилия,
  // «Ратмир» — имя. Ошибиться в эту сторону безопаснее: неузнанное имя
  // уводит в нейтральное обращение, а не в обращение по фамилии.
  if (!out.first && !out.patronymic && parts.length === 1 && !SURNAME_END.test(parts[0])) {
    out.first = parts[0];
    out.surname = '';
  }
  return out;
}

/**
 * Сокращённая запись для блока «Кому» документа: «Беляев А.В.», «Беляев А.»,
 * «Беляев». Пусто, если фамилии нет — строка с одним именем в реквизитах
 * ничего не сообщает, и её в документе не печатают.
 */
export function shortFio(raw: string): string {
  const p = parsePerson(raw);
  if (!p.surname) return '';
  const letters = p.initials
    ? p.initials.replace(/\./g, '').split('')
    : [p.first, p.patronymic].filter(Boolean).map((w) => w[0]);
  const tail = letters.map((l) => `${l.toUpperCase()}.`).join('');
  return tail ? `${p.surname} ${tail}` : p.surname;
}

/** «Уважаемая Екатерина» / «Уважаемый Иван Иванович» / «Уважаемый коллега». */
export function salutation(raw: string): string {
  // В поле контактного лица нередко вписывают организацию. Обращаться
  // «Уважаемая Ромашка» к ООО «Ромашка» хуже, чем нейтральное приветствие.
  // Проверяем по словам, а не через \b: в JS граница слова определена для
  // латиницы, и на кириллице такая проверка молча не срабатывает.
  const words = (raw || '').replace(/[«»"'()]/g, ' ').split(/[\s,.]+/);
  if (words.some((w) => ORG_FORM.test(w))) return 'Уважаемые господа!';
  const name = addressName(raw);
  // Ни имени, ни отчества — только фамилия или инициалы. Обращение по
  // фамилии звучит как вызов к доске, поэтому нейтральное «коллега».
  if (!name) return nameParts(raw).length ? 'Уважаемый коллега!' : 'Уважаемые господа!';
  const g = detectGender(raw);
  const word = g === 'female' ? 'Уважаемая' : g === 'male' ? 'Уважаемый' : 'Уважаемый(ая)';
  return `${word} ${name}!`;
}
