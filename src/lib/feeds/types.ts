/**
 * Типы универсального механизма товарных фидов.
 *
 * Архитектура (решение руководителя 29.08.2026): механизм фидов отделён от
 * логики сайта. Ядро (отбор → ранжирование → лимит) одно на всех, а
 * особенности конкретного сервиса (формат файла, дополнительные фильтры,
 * лимит позиций) описываются «спецификацией фида» и живут в реестре
 * (registry.ts). Страницы сайта — тонкие обёртки: берут спецификацию из
 * реестра и отдают готовый документ.
 */
import type { Product } from '../types';

/** Нормализованное предложение — общий словарь всех форматов фидов. */
export interface FeedOffer {
  /** Уникальный id оффера (sku товара). */
  id: string;
  name: string;
  /** Абсолютный URL карточки на сайте. */
  url: string;
  /** Цена к оплате (с учётом активной акции), ₽. */
  price: number;
  /** Зачёркнутая базовая цена при активной акции. */
  oldPrice: number | null;
  /** ISO-валюта предложения (RUR — историческое обозначение рубля в YML). */
  currencyId: string;
  /** Название категории каталога (числовой id присваивает сериализатор). */
  categoryName: string;
  /** Абсолютный URL картинки. */
  picture: string;
  /** Плоский текст без HTML, ограничен лимитом сервиса. */
  description: string;
  vendor: string | null;
  /** Артикул продавца. */
  vendorCode: string;
  /** Условия продажи (показ в сниппете). */
  salesNotes?: string;
}

/** Контекст отбора: всё внешнее ядро получает параметрами (чистые функции). */
export interface FeedSelectOptions {
  /** Спрос Вордстата по вендорам — ключ ранжирования. */
  demand: Record<string, number>;
  /** Максимум позиций (0 или undefined — без лимита). */
  maxOffers?: number;
  /** Дополнительный фильтр сервиса поверх базовых требований. */
  extraFilter?: (p: Product) => boolean;
  /** Момент расчёта акционных цен (для тестов). */
  now?: Date;
}

/** Метаданные магазина для заголовка фида. */
export interface FeedShopInfo {
  name: string;
  company: string;
  url: string;
}

/** Спецификация фида конкретного сервиса — единица подключения в реестре. */
export interface FeedSpec {
  /** Машинный идентификатор (совпадает с именем маршрута). */
  id: string;
  /** Название сервиса-потребителя — для отчётов и журналов. */
  service: string;
  /** Путь на сайте, по которому сервис забирает фид. */
  path: string;
  /** MIME-тип ответа (Яндекс требует один из объявленных в справке). */
  contentType: string;
  /** Переменная окружения с лимитом позиций для этого фида. */
  maxOffersEnv: string;
  /** Дополнительный фильтр сервиса (поверх базовых требований). */
  extraFilter?: (p: Product) => boolean;
  /** Собрать документ фида из уже отобранных товаров. */
  build: (products: Product[], opts: { now?: Date }) => string;
}
