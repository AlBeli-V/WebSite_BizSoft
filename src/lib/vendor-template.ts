/**
 * Выключатель универсального шаблона страницы производителя (движок v2).
 *
 * Движок добавляет к лендингу блоки утверждённого макета от 15.09.2026:
 * ценность для бизнеса под заголовком, карту направлений с фильтром сетки и
 * подачу длинного хвоста строками вместо стены карточек. Появляются они
 * только там, где контент вендора несёт нужные поля (`businessValue`,
 * `categories`), — остальные сто страниц движок не трогает даже включённым.
 *
 * Если результат не устроит, откат не требует ни правки кода, ни отката
 * коммитов. Достаточно задать на сервере
 *
 *     PUBLIC_VENDOR_TEMPLATE_V2=0
 *
 * и пересобрать: страница вернётся к прежней композиции, а написанный
 * контент останется на месте и дождётся следующего решения.
 *
 * Значение по умолчанию — включено: переменная задаётся только тогда, когда
 * движок нужно погасить.
 */
export const VENDOR_TEMPLATE_V2 = import.meta.env.PUBLIC_VENDOR_TEMPLATE_V2 !== '0';

/**
 * С какого числа позиций длинный хвост подаётся строками, а не карточками.
 *
 * Правило макета: карточка — это место для состава плана и счётчика, и она
 * оправдана, пока карточек единицы. Двадцать две карточки подряд читаются
 * не как линейка, а как стена, и направление в ней ищут прокруткой. Ниже
 * порога подача не меняется: у вендора с двумя-тремя позициями строки
 * выглядели бы обрывком таблицы.
 */
export const ROW_LAYOUT_MIN = 8;
