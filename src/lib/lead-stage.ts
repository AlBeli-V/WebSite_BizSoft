/**
 * Даты стадии заявки — один расчёт на все источники смены стадии.
 *
 * По этим датам считается срок сделки в ежедневном отчёте, поэтому ставит их
 * система, а не человек: при первом пропуске воронка начала бы врать. До
 * 14.09.2026 расчёт жил единственной копией в кабинете, и этого хватало —
 * менять стадию умел только менеджер. С обратным каналом из Bitrix24
 * (`/api/b24/hook`) источников стало два, а копий расчёта должно остаться
 * ноль: разъехавшиеся правила дали бы в отчёте две разные воронки.
 *
 * Модуль лежит в src/lib, а не в src/crm: туда сетевым обработчикам ходить
 * нельзя (tests/crm-isolation.test.ts). Регламент перехода — по-прежнему в
 * src/crm/stages.ts, и проверяет его только кабинет: из портала стадия
 * приходит как свершившийся факт, а не как заявка на переход.
 */

export interface StageDatesSource {
  /** Дата квалификации, уже стоящая у заявки: она не перезаписывается. */
  qualified_at?: unknown;
}

/**
 * Поля, которые добавляются к правке заявки при смене стадии.
 *
 * @param status новая стадия; `undefined` — стадию не меняли, дат не будет
 * @param current заявка, какой она лежит в базе сейчас
 * @param now момент правки в ISO — передаётся, чтобы тест не зависел от часов
 */
export function stageDatePatch(
  status: string | undefined,
  current: StageDatesSource,
  now: string,
): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  if (!status) return out;
  if (status === 'qualified' && !current.qualified_at) out.qualified_at = now;
  if (status === 'won' || status === 'lost') out.closed_at = now;
  // Заявка, вернувшаяся в работу, не должна тащить за собой причину отказа:
  // иначе в отчёте она числится живой и отказной одновременно.
  if (status !== 'lost') out.lost_reason = null;
  return out;
}
