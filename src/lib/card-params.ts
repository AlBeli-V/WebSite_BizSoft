/**
 * Блок «Основные параметры» карточки товара: состав, порядок и значения.
 *
 * Постановка руководителя 14.09.2026. Правило глобальное: одинаковая
 * структура и последовательность во всём каталоге, значения — семантически
 * верные для каждого вида позиции. Поэтому строки собираются здесь, а не
 * перечисляются в разметке: шаблон печатает то, что вернула эта функция, и
 * порядок нельзя поменять на одной карточке, не поменяв его везде.
 *
 * Значения берутся из данных позиции и из уже посчитанных полей карточки —
 * тех же, что стоят в плашках, в подзаголовке и в блоке цены. Отдельной
 * логики у параметров нет: расхождение между навигацией и параметрами
 * («в плашке одна категория, в таблице другая») — как раз то, ради чего
 * этот модуль появился.
 */
import { parseSku, SKU_UNITS, type SkuUnit } from './sku';
import { unitNoun } from './product-commerce';
import { TERM } from './card-display';

/** Канонический порядок. Другой последовательности в каталоге не бывает. */
export const PARAM_ORDER = [
  'Производитель',
  'Категория',
  'Тип плана',
  'Срок',
  'Расчётная единица',
  // Короткие подписи вместо «Минимального количества» и «Переназначения
  // пользователей»: длинные ложились на телефоне в две строки, а строка
  // параметра обязана оставаться строкой (постановка руководителя 14.09.2026).
  'Мин. кол-во',
  'Трансфер',
  'Управление',
  'НДС',
  'Артикул',
] as const;
export type ParamKey = (typeof PARAM_ORDER)[number];

export interface CardParamRow {
  /** Подпись без двоеточия — его ставит разметка. */
  key: string;
  value: string;
}

/**
 * Расчётная единица по сегменту `ЕДИНИЦА` артикула (`docs/rules/sku-system.md`).
 * Сегмент и есть ответ на вопрос «за что платят», поэтому механическое
 * «Рабочее место» всему каталогу здесь невозможно: у номинала выйдет «Сумма»,
 * у серверной лицензии — «Сервер».
 */
export const SKU_UNIT_LABEL: Record<SkuUnit, string> = {
  USER: 'Рабочее место',
  DEV: 'Устройство',
  SRV: 'Сервер',
  CCU: 'Плавающая лицензия',
  ORG: 'Организация',
  PROJ: 'Проект',
  PACK: 'Пакет объёма',
  NOM: 'Сумма',
};

/** «12 месяцев», «24 месяца»: в параметрах срок называется месяцами. */
function monthsWord(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  const word = m100 >= 11 && m100 <= 19 ? 'месяцев'
    : m10 === 1 ? 'месяц'
    : m10 >= 2 && m10 <= 4 ? 'месяца'
    : 'месяцев';
  return `${n} ${word}`;
}

/**
 * Срок в строке параметров: годы разворачиваются в месяцы («1 год» →
 * «12 месяцев»), бессрочная лицензия обозначается знаком бесконечности, у
 * пополнения остаётся «до истечения баланса» (постановка руководителя
 * 14.09.2026). В подзаголовке под H1 срок по-прежнему пишется годами
 * (`docs/rules/card-title.md`): там он читается фразой, здесь — значением
 * таблицы, и месяцы сравнимы между позициями.
 */
export function paramTerm(term: string | null | undefined): string {
  if (!term) return '';
  if (term === TERM.perpetual) return '∞';
  if (term === TERM.balance) return TERM.balance;
  const years = term.trim().match(/^(\d+)\s*(?:год|года|лет)$/i);
  if (years) return monthsWord(12 * Number(years[1]));
  return term;
}

/**
 * Единица расчёта позиции.
 *
 * Порядок источников: слово оператора в каталоге (`unit_label`) — самое
 * точное, им же размечают пакеты кредитов, где «Сумма» сказала бы не то;
 * затем сегмент артикула; затем подпись счётчика из контента вендора.
 * Догадок по названию нет ни на одном шаге.
 */
export function unitLabel(sku: string | null | undefined, unitField: string | null | undefined, qtyLabel: string): string {
  const manual = unitField?.trim();
  if (manual) return manual.charAt(0).toUpperCase() + manual.slice(1);
  const unit = parseSku(sku)?.unit as SkuUnit | undefined;
  if (unit && unit in SKU_UNITS) return SKU_UNIT_LABEL[unit];
  return unitNoun(qtyLabel);
}

export interface CardParamsInput {
  /** Полное юридическое наименование производителя (`vendorLegal`). */
  vendorLegal: string;
  /** Категория из плашки под крошками — та же, что в навигации. */
  category: string;
  /** «Командный» / «Индивидуальный»; пусто — деления нет. */
  planShort: string;
  /** Срок из данных позиции (`termLabel`): «1 год», «бессрочно», …
   *  Пусто у договорной позиции — строки тогда нет. */
  term: string | null;
  sku: string;
  unitField?: string | null;
  qtyLabel: string;
  /** Минимум заказа — тот же, что в счётчике и в ИТОГО (`commerce.minQty`). */
  minQty: number;
  /** Переназначение пользователей: то же значение, что в колонке ТРАНСФЕР. */
  transfer: string;
  /** Как управляется тариф — из контента вендора; пусто, если не заведено. */
  management?: string | null;
  /** Ставка НДС позиции; 0 — строки нет. */
  vat: number;
  /**
   * Строки вида позиции: регионы и число номиналов у подарочной карты.
   * Встают после «Управления», чтобы канонический порядок не рвался.
   */
  extra?: CardParamRow[];
}

/** Строки блока в каноническом порядке. Пустые значения не выводятся. */
export function cardParams(input: CardParamsInput): CardParamRow[] {
  const rows: CardParamRow[] = [
    { key: 'Производитель', value: input.vendorLegal },
    { key: 'Категория', value: input.category },
    // Деления на командный и индивидуальный может не быть вовсе — тогда
    // «Универсальный», как в плашке над заголовком. Пустой строки здесь не
    // бывает: покупатель читает таблицу сверху вниз и пропуск заметит.
    { key: 'Тип плана', value: input.planShort || 'Универсальный' },
    { key: 'Срок', value: paramTerm(input.term) },
    { key: 'Расчётная единица', value: unitLabel(input.sku, input.unitField, input.qtyLabel) },
    { key: 'Мин. кол-во', value: String(Math.max(1, Math.floor(input.minQty) || 1)) },
    { key: 'Трансфер', value: input.transfer || '' },
    { key: 'Управление', value: input.management?.trim() || '' },
    ...(input.extra ?? []),
    // Пояснения под строкой налога нет (решение руководителя 14.09.2026):
    // «включён в цену, принимается к вычету» живёт в ответах о документах и
    // в статье о закрывающих документах, а не в таблице параметров.
    ...(input.vat > 0 ? [{ key: 'НДС', value: `${input.vat}% (включено в стоимость)` }] : []),
    { key: 'Артикул', value: input.sku },
  ];
  return rows.filter((r) => r.value.trim().length > 0);
}
