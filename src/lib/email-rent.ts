/**
 * Аренда адреса электронной почты для регистрации личного кабинета.
 *
 * Постановка руководителя 15.09.2026. Вопрос задаётся один раз — в шапке
 * спецификации (`/cart`), а не в каждой карточке товара: адреса нужны не
 * товару, а покупателю, у которого нет почты вне зоны .ru, и ответ на этот
 * вопрос один на всю подборку. Поэтому в каталоге поля-галочки нет и
 * размечать шестьсот карточек не требуется.
 *
 * Услуга применяется ВЫБОРОЧНО и только к тем позициям, где учётная запись
 * действительно нужна и живёт ровно год: годовая подписка на сервис или
 * дополнение к нему. Бессрочный ключ активации, пополнение баланса,
 * подарочная карта и услуги производителя аренды почты не получают — там
 * либо нет привязки к кабинету, либо нет годового срока, и приписать им
 * восемь тысяч значило бы продать то, чего нет.
 */
import { parseSku, termMonths } from './sku';

/** Цена аренды одного адреса на один календарный год, ₽ (решение руководителя 15.09.2026). */
export const EMAIL_RENT_PRICE = 8000;

/** Срок аренды — один календарный год. Другого срока у услуги нет. */
export const EMAIL_RENT_MONTHS = 12;

/**
 * Нужна ли позиции аренда почты, если покупатель её выбрал.
 *
 * Условие читается из сегментов артикула (docs/rules/sku-system.md), а не из
 * названия: вид позиции (LIC — подписка или лицензия, ADD — дополнение) и
 * срок ровно 12 месяцев. Позиция без системного артикула (черновик, архив)
 * услуги не получает: о её сроке ничего не известно.
 */
export function emailRentApplies(sku: string | null | undefined): boolean {
  const parsed = parseSku(sku);
  if (!parsed) return false;
  if (parsed.kind !== 'LIC' && parsed.kind !== 'ADD') return false;
  return termMonths(parsed.term) === EMAIL_RENT_MONTHS;
}

/**
 * Цена единицы с арендой. Аренда считается за единицу, а не за строку:
 * личный кабинет регистрируется на каждое рабочее место, и колонки
 * спецификации обязаны сходиться (ЦЕНА × КОЛ-ВО = СУММА).
 */
export function unitPriceWithRent(price: number, sku: string, rentOn: boolean): number {
  return rentOn && emailRentApplies(sku) ? price + EMAIL_RENT_PRICE : price;
}
