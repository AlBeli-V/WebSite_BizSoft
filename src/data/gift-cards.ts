/**
 * Редакторский контент страниц подарочных карт (product_type = gift_card).
 *
 * Данные — номиналы, регионы, цены — живут в Directus (варианты с parent_sku),
 * а здесь то, чему в полях карточки места нет: разделы описания, порядок
 * активации, FAQ. Та же схема, что у лендингов производителей
 * (src/data/vendor-content.ts): данные из базы, текст из кода. Ключ — slug
 * родительской карточки. Карта без записи здесь рендерится с типовыми
 * блоками страницы товара и селектором вариантов.
 *
 * Факты об Apple Gift Card изложены по документации поддержки Apple
 * («Погашение подарочной карты», «Баланс Apple Account», «Изменение страны
 * или региона»); из сессии эти страницы недоступны, поэтому формулировки
 * осторожные: без обещаний конкретных сервисов, состав которых в стране
 * определяет Apple.
 */

export interface GiftCardSection { h2: string; paragraphs: string[]; bullets?: string[] }
export interface GiftCardRegionContent { code: string; h2: string; text: string; note?: string }

export interface GiftCardContent {
  /** Короткое имя для кнопок и подписей («Apple Gift Card»). */
  shortName: string;
  /** Подпись к номиналу под селектором. */
  denominationNote: string;
  /** Предупреждение о регионе — выводится заметно рядом с выбором. */
  regionWarning: string;
  /** Пояснение об ограниченном наличии и нескольких кодах. */
  availabilityNote: string;
  /** Отказ от статуса партнёра. */
  disclaimer: string;
  /** Разделы по регионам (порядок — как в REGION_ORDER). */
  regions: GiftCardRegionContent[];
  /** Содержательные разделы страницы (H2 + абзацы). */
  sections: GiftCardSection[];
  /** Инструкция активации: заголовок H2, шаги и предупреждение. */
  activation: { h2: string; intro: string; steps: string[]; warning: string };
  faq: { q: string; a: string }[];
}

