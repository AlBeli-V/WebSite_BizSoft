/**
 * Условия работы BIZSoft одним источником: договор, счёт, ЭДО, сроки,
 * стоимость, валюта оплаты, порядок сделки.
 *
 * Раньше эти тексты жили тремя независимыми массивами в `/faq`,
 * `/how-we-work` и `/pricing`, и AI-агент покупателя не мог получить их
 * вообще — WebMCP-слой читает каталог, а не разметку страниц. При этом
 * по данным Growth Intelligence конверсию даёт именно контент об условиях
 * покупки, а не карточки товаров. Поэтому источник один: страницы
 * рендерят его через `policyFaq()`, инструмент `search_policies` ищет
 * по нему же (`src/lib/policy-search.ts`).
 *
 * Правило: текст правится ЗДЕСЬ. Строка, добавленная в `.astro` мимо
 * этого файла, снова разъедет страницу и ответ агенту — тест
 * `tests/policies.test.ts` следит, чтобы страницы не заводили своих
 * массивов условий.
 */

export interface PolicyItem {
  /** Стабильный машинный id — ссылка для тестов и отладки. */
  id: string;
  question: string;
  answer: string;
  /** Страница, где человека ждёт этот же текст (агент даёт ссылку туда). */
  path: string;
  /** Синонимы, которыми спрашивают об этом же, — только для поиска. */
  keywords: string;
}

