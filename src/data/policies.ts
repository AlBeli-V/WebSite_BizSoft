/**
 * Все записи базы условий — то, по чему ищет агент. Порядок сделки идёт
 * последней: её ответ длиннее остальных вместе взятых и совпадает почти с
 * любым вопросом, поэтому при равном числе совпавших слов выигрывать должен
 * узкий ответ («дадите закрывающие документы» — про документы, а не пересказ
 * всех семи шагов). Своими словами — «процесс», «этапы», «как проходит» —
 * запись находится сама.
 */
export const ALL_POLICIES: PolicyItem[] = [...POLICIES, PROCESS_POLICY];

/** Вопрос-ответы одной страницы в формате компонента FAQ (порядок сохраняется). */
export function policyFaq(path: string): { q: string; a: string }[] {
  return POLICIES.filter((p) => p.path === path).map((p) => ({ q: p.question, a: p.answer }));
}

