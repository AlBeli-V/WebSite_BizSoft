/**
 * Обращение по имени из формы заявки.
 *
 * Первая строка письма — единственное место, где ошибка видна мгновенно и
 * читается как небрежность. Поэтому род определяется по отчеству, где оно
 * есть, а при неуверенности пишется через скобку.
 */
import { describe, expect, it } from 'vitest';
import { salutation, detectGender, addressName } from '../src/lib/salutation';

describe('обращение', () => {
  it('отчество определяет род однозначно', () => {
    expect(salutation('Иванов Иван Иванович')).toBe('Уважаемый Иван Иванович!');
    expect(salutation('Петрова Мария Сергеевна')).toBe('Уважаемая Мария Сергеевна!');
  });

  it('без отчества обращаемся по имени', () => {
    expect(salutation('Екатерина Кувшинова')).toBe('Уважаемая Екатерина!');
    expect(salutation('Никита Смирнов')).toBe('Уважаемый Никита!');
  });

  it('порядок «фамилия имя» и «имя фамилия» даёт одно и то же', () => {
    expect(addressName('Кувшинова Екатерина')).toBe('Екатерина');
    expect(addressName('Екатерина Кувшинова')).toBe('Екатерина');
  });

  it('женское имя на согласную не становится мужским', () => {
    expect(detectGender('Любовь Орлова')).toBe('female');
    expect(salutation('Любовь Орлова')).toBe('Уважаемая Любовь!');
  });

  it('мужское имя на -а не становится женским', () => {
    expect(detectGender('Никита')).toBe('male');
    expect(detectGender('Илья Муромец')).toBe('male');
  });

  it('организация в поле имени — нейтральное приветствие', () => {
    // Обращаться «Уважаемая Ромашка» к ООО хуже, чем формально.
    expect(salutation('ООО «Ромашка»')).toBe('Уважаемые господа!');
    expect(salutation('ИП Сидоров')).toBe('Уважаемые господа!');
  });

  it('пустое поле не ломает письмо', () => {
    expect(salutation('')).toBe('Уважаемые господа!');
    expect(salutation('   ')).toBe('Уважаемые господа!');
  });

  it('должность в поле имени не становится обращением', () => {
    expect(addressName('Директор Смирнов Пётр Ильич')).toBe('Пётр Ильич');
  });
});
