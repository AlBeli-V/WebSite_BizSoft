/**
 * Обращение по имени из формы заявки.
 *
 * Первая строка письма — единственное место, где ошибка видна мгновенно и
 * читается как небрежность. Поэтому род определяется по отчеству, где оно
 * есть, а при неуверенности пишется через скобку.
 */
import { describe, expect, it } from 'vitest';
import { salutation, detectGender, addressName, shortFio } from '../src/lib/salutation';

describe('обращение', () => {
  it('отчество определяет род однозначно', () => {
    expect(salutation('Иванов Иван Иванович')).toBe('Уважаемый Иван Иванович!');
    expect(salutation('Петрова Мария Сергеевна')).toBe('Уважаемая Мария Сергеевна!');
  });

  it('без отчества обращаемся по имени', () => {
    expect(salutation('Екатерина Кувшинова')).toBe('Уважаемая Екатерина!');
    expect(salutation('Никита Смирнов')).toBe('Уважаемый Никита!');
  });

  it('порядок «фамилия имя» и «имя фамилия» даёт одно и то же', () => {
    expect(addressName('Кувшинова Екатерина')).toBe('Екатерина');
    expect(addressName('Екатерина Кувшинова')).toBe('Екатерина');
  });

  it('женское имя на согласную не становится мужским', () => {
    expect(detectGender('Любовь Орлова')).toBe('female');
    expect(salutation('Любовь Орлова')).toBe('Уважаемая Любовь!');
  });

  it('мужское имя на -а не становится женским', () => {
    expect(detectGender('Никита')).toBe('male');
    expect(detectGender('Илья Муромец')).toBe('male');
  });

  it('организация в поле имени — нейтральное приветствие', () => {
    // Обращаться «Уважаемая Ромашка» к ООО хуже, чем формально.
    expect(salutation('ООО «Ромашка»')).toBe('Уважаемые господа!');
    expect(salutation('ИП Сидоров')).toBe('Уважаемые господа!');
  });

  it('пустое поле не ломает письмо', () => {
    expect(salutation('')).toBe('Уважаемые господа!');
    expect(salutation('   ')).toBe('Уважаемые господа!');
  });

  it('должность в поле имени не становится обращением', () => {
    expect(addressName('Директор Смирнов Пётр Ильич')).toBe('Пётр Ильич');
  });
});

describe('фамилия и инициалы — нейтральное обращение', () => {
  // Правило руководителя 16.09.2026: по фамилии в первой строке письма не
  // обращаемся, это звучит как вызов к доске.
  it('«Беляев А.В.» и «Беляев А» дают «Уважаемый коллега!»', () => {
    expect(salutation('Беляев А.В.')).toBe('Уважаемый коллега!');
    expect(salutation('Беляев А')).toBe('Уважаемый коллега!');
    expect(salutation('Беляев')).toBe('Уважаемый коллега!');
  });

  it('полное ФИО — имя и отчество, фамилия и имя — только имя', () => {
    expect(salutation('Беляев Алексей Васильевич')).toBe('Уважаемый Алексей Васильевич!');
    expect(salutation('Беляев Алексей')).toBe('Уважаемый Алексей!');
  });
});

describe('сокращённая запись для блока «Кому»', () => {
  it('фамилия с инициалами по составу поля', () => {
    expect(shortFio('Беляев Алексей Васильевич')).toBe('Беляев А.В.');
    expect(shortFio('Беляев Алексей')).toBe('Беляев А.');
    expect(shortFio('Беляев А.В.')).toBe('Беляев А.В.');
    expect(shortFio('Беляев')).toBe('Беляев');
  });

  it('одно имя строки не даёт: в реквизитах она ничего не сообщает', () => {
    expect(shortFio('Алексей')).toBe('');
    expect(shortFio('')).toBe('');
  });

  it('порядок слов не важен', () => {
    expect(shortFio('Алексей Васильевич Беляев')).toBe('Беляев А.В.');
  });
});

describe('регистр имени из формы', () => {
  // Замечание руководителя 19.09.2026: «Беляев алексей» уходил в документ
  // дословно, и КП выглядело небрежно.
  it('строчные буквы поднимаются до прописной', () => {
    expect(salutation('беляев алексей васильевич')).toBe('Уважаемый Алексей Васильевич!');
    expect(salutation('Беляев алексей')).toBe('Уважаемый Алексей!');
    expect(shortFio('беляев алексей васильевич')).toBe('Беляев А.В.');
  });

  it('набранное капсом приводится к обычному виду', () => {
    expect(salutation('БЕЛЯЕВ АЛЕКСЕЙ ВАСИЛЬЕВИЧ')).toBe('Уважаемый Алексей Васильевич!');
    expect(shortFio('БЕЛЯЕВ АЛЕКСЕЙ')).toBe('Беляев А.');
  });

  it('инициалы в любом регистре становятся прописными', () => {
    expect(shortFio('беляев а.в.')).toBe('Беляев А.В.');
    expect(shortFio('БЕЛЯЕВ А.В.')).toBe('Беляев А.В.');
  });

  it('составная фамилия получает прописную в каждой части', () => {
    expect(shortFio('петров-водкин кузьма сергеевич')).toBe('Петров-Водкин К.С.');
  });

  it('смешанный регистр набран намеренно и не трогается', () => {
    // «МакДональд» после приведения стал бы «Макдональд».
    expect(shortFio('МакДональд Алексей')).toBe('МакДональд А.');
  });

  it('род определяется после приведения регистра', () => {
    expect(detectGender('петрова мария сергеевна')).toBe('female');
    expect(salutation('петрова мария сергеевна')).toBe('Уважаемая Мария Сергеевна!');
  });
});
