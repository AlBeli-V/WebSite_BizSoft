/**
 * Тег Метрики грузится напрямую (инцидент 04–08.09.2026).
 *
 * 04.09 файл счётчика перевели на кэширующий прокси своего домена
 * (/m/tag.js). Сайт после этого перестал собирать визиты: 04.09 — 45,
 * 03.09 — 69, 02.09 — 80, а с 05.09 — 0–1 в день при живой рекламе и
 * живой органике. Прокси отвечал 200 и отдавал файл нужного размера,
 * поэтому onerror не срабатывал и запасной адрес не подключался —
 * браузер считал скрипт загруженным, а счётчик молчал четверо суток.
 *
 * Проверка держит два условия: адрес тега — домен Метрики, и подмена
 * пути не возвращается молча. Заменить адрес можно, но только вместе с
 * проверкой, что счётчик реально инициализировался в браузере: код
 * ответа и размер файла об этом не говорят ничего.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

const analytics = readFileSync('src/components/Analytics.astro', 'utf8');
const code = analytics
  .split('\n')
  .filter((l) => !l.trim().startsWith('//') && !l.trim().startsWith('*'))
  .join('\n');

describe('источник тега Метрики', () => {
  it('тег грузится с домена Метрики', () => {
    expect(code).toContain("'https://mc.yandex.ru/metrika/tag.js?id='");
  });

  it('локальный путь тега в коде не используется', () => {
    expect(code).not.toMatch(/['"]\/m\/tag\.js['"]/);
    expect(code).not.toMatch(/src\s*=\s*proxied/);
  });

  it('счётчик подключается ровно одним адресом', () => {
    expect(analytics.match(/metrika\/tag\.js/g)?.length).toBe(1);
  });
});
